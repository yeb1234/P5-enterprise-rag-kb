"""llmwiki —— LLM Wiki 路由的纯函数包：门禁、构建、检索。

## LLM Wiki 是什么（与向量检索、图谱检索的分工）

同一个问题三路取证，各取所需：
- 向量检索：从**原文**里找证据（合同、手册的原始段落）；
- 图谱检索：沿**关系**找线索（谁和谁有关联、多跳）；
- LLM Wiki：读**整理好的业务知识**——概念、流程、规则。它不存原文，
  存的是「模型把少量资料整理出来的 Markdown 页面 + 每条结论的证据链」。

## 为什么它必须先过门禁

Wiki 是「先把资料整理好、再被反复查阅」的东西，只在三种条件都稳定时才成立：
1. **业务场景已确定**——没有场景就没有整理口径，整理出来的东西谁也用不上；
2. **信源稳定**——资料在整理后变过，页面就是旧的；
3. **新鲜度稳定**——资料里有已过期 / 未生效的内容，或大量陈旧内容，整理出来的是过期知识。

三条缺一，Wiki 不启动（路由报告里写明缺哪条），而不是「尽力而为」——
拿过期规则去回答业务问题，比不回答更糟。

## 与 webapp/ 的边界
本包不碰数据库、不取模型：门禁与检索是纯函数，构建只依赖传入的 `llm.complete()`。
读 PG、取模型、脱敏、落库都在 `webapp/kb_routes.py`。
"""
