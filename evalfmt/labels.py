"""评估集标注：问题 → 期望命中文档 + 期望事实。

标注原则（被问到时按这个讲）：
1. **一问一事实**。每道题的答案在语料里是唯一字符串，所以「召回对不对」和
   「答得对不对」都能机器判定，不靠人眼看。
2. **期望事实必须是文中原样出现的字符串**，否则无法判断「引用的那段是否真的支持答案」。
3. 负例分两类：
   - `negative`：库里根本没有这个信息（营收预测），期望**拒答/降级**；
   - `trap`：同品类不同实体（问 MX-9900 的保修期，库里只有 KX-2400），
     期望**不把 KX 的参数套到 MX 上**——这是最容易被模型糊过去的一类。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Case:
    case_id: str
    kind: str            # factual | negative | trap
    question: str
    doc: str             # 期望命中的文件名；负例为空串
    fact: str            # 期望事实（文中原样字符串）；负例/陷阱为空串
    note: str = ""


# 9 道正例：一份可检索文档一道，覆盖 8 种格式（PDF 两道，验证「格式换了召回还准不准」）
